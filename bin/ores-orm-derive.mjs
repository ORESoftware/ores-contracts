#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { deriveOrmProjection, selectPublic, buildArtifacts } from '../src/orm-derived/index.mjs';

if (process.env.ORES_ORM_LEGACY_BOOTSTRAP !== '1') {
  throw new Error(
    'ores-orm-derive is a deprecated bootstrap-only compatibility shim; set ORES_ORM_LEGACY_BOOTSTRAP=1 only for non-publishable evidence. Canonical ORM-derived codegen lives in ORESoftware/ores-orm-core and public promotion requires separate TJSV admission.',
  );
}

const required = {
  diesel: process.env.ORES_ORM_DIESEL,
  seaorm: process.env.ORES_ORM_SEAORM,
  policy: process.env.ORES_ORM_POLICY,
  out: process.env.ORES_ORM_OUT,
};
for (const [name, value] of Object.entries(required)) {
  if (!value) throw new Error(`missing required legacy bootstrap environment variable ORES_ORM_${name.toUpperCase()}`);
}

const [dieselSource, seaOrmSource, policyText] = await Promise.all([
  fs.readFile(required.diesel, 'utf8'),
  fs.readFile(required.seaorm, 'utf8'),
  fs.readFile(required.policy, 'utf8'),
]);
const policy = JSON.parse(policyText);
const full = deriveOrmProjection({
  dieselSource,
  seaOrmSource,
  namespace: policy.source_namespace || 'orm.derived',
});
const publicProjection = selectPublic(full, policy);
const files = buildArtifacts(publicProjection);
const digest = (value) => crypto.createHash('sha256').update(value).digest('hex');

for (const [relativePath, content] of Object.entries(files)) {
  const destination = path.join(required.out, relativePath);
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.writeFile(destination, content);
}

await fs.writeFile(
  path.join(required.out, 'receipt.json'),
  JSON.stringify(
    {
      schema: 'ores.orm-derived-receipt/v1',
      role: 'legacy_bootstrap_evidence_only',
      publication: 'blocked_pending_rust_engine_and_tjsv_admission',
      publishable: false,
      diesel_sha256: digest(dieselSource),
      seaorm_sha256: digest(seaOrmSource),
      policy_sha256: digest(policyText),
      outputs: Object.fromEntries(Object.entries(files).map(([key, value]) => [key, digest(value)])),
    },
    null,
    2,
  ) + '\n',
);

await fs.writeFile(
  path.join(required.out, 'DO_NOT_PUBLISH.md'),
  '# Legacy bootstrap evidence only\n\nThis output was generated by the deprecated Node compatibility shim. It is not release/publication evidence. Re-generate with `ORESoftware/ores-orm-core` and obtain separate TJSV admission before promotion.\n',
);
